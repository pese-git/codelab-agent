"""Доменные события журнала сессии (шаг 3a ADR-008).

Журнал — упорядоченная последовательность фактов диалога. ACP-нотификация и
LLM-история из него **выводятся**, поэтому событие описано в терминах домена и
ничего не знает ни о `sessionUpdate`, ни о camelCase: форму wire знает проекция
(`mapping/journal_mapper.py`). Этим отменяется запись ADR-006 о том, что
`events_history` — постоянная wire-граница.

Шаг 3a вводит только модель: на диск по-прежнему уезжает нынешняя форма, её
отдаёт та же проекция. Смена формата документа — шаг 3b.

Гранулярность — **сообщение**, не чанк потока. Это замер, а не допущение: на
живом документе `agent_message_chunk` пришёлся ровно по одному на текст
ассистента, `user_message_chunk` — по одному на блок промпта (разведка формы
события, 2026-08-06). ACP-чанк остаётся деталью проекции.

Блоки контента остаются непрозрачными `dict`: их форма принадлежит ACP Content
Types, домен их не интерпретирует и не пересобирает — иначе проекция перестала
бы быть байт-идентичной.
"""

from __future__ import annotations

from collections.abc import Iterable
from dataclasses import dataclass, field
from datetime import datetime
from typing import Any

__all__ = [
    "AgentMessageRecorded",
    "JournalEntry",
    "SessionJournal",
    "PlanRecorded",
    "RequestedToolCall",
    "SessionEvent",
    "SessionInfoRecorded",
    "ToolCallAnswered",
    "ToolCallStarted",
    "ToolCallStatusChanged",
    "UnknownUpdateRecorded",
    "UserMessageRecorded",
]


@dataclass(frozen=True)
class UserMessageRecorded:
    """Промпт пользователя — одно событие на сообщение, блоки внутри.

    **Прежде писалось по событию на блок, и это было ошибкой** (шаг 4e). Правило
    «гранулярность — сообщение» объявлено в шаге 3a, но пользовательская сторона
    его нарушала, а замер этого не заметил: во всех наблюдавшихся промптах был
    ровно один блок. `Session.add_user_message` кладёт **одно** сообщение из всех
    блоков, поэтому многоблочный промпт (`@`-упоминание с вложением в Zed: текст
    плюс `resource_link`) дал бы проекции N сообщений вместо одного, то есть
    изменил бы форму диалога и сбросил prompt cache.

    Порядок блоков — часть содержимого: реплей отдаёт по чанку на блок, склейка
    недопустима.
    """

    blocks: list[dict[str, Any]]


@dataclass(frozen=True)
class RequestedToolCall:
    """Вызов в том виде, в каком его запросила модель.

    Три поля, которых нет в `ToolCallStarted`, и все три принадлежат модели, а не
    ACP: `id` — идентификатор из её ответа (`chatcmpl-…`), `name` — имя,
    которым она инструмент назвала (`terminal_create`), `arguments` — аргументы,
    как она их прислала.

    Имя расходится с ACP-именем инструмента (`terminal/create`) в 19 случаях из
    30 по замеру, поэтому вывести его из `title` события `ToolCallStarted`
    нельзя. Это тот же класс, что расхождение текста ответа (шаг 4d).

    Здесь же живёт обратный индекс `llm_id → ToolCallId` из раздела 2 ADR: он
    вводится вместе со своим потребителем — проекцией `history`, — а не раньше.
    """

    id: str
    name: str
    arguments: dict[str, Any]


@dataclass(frozen=True)
class AgentMessageRecorded:
    """Ответ модели: текст и запрошенные ею вызовы — одно событие на сообщение.

    `tool_calls` добавлены в шаге 4e: без них assistant-запись `history`
    **невыводима**, и не по одной причине, а по четырём — нет идентификатора
    модели, нет её имени инструмента, нет аргументов и нет границ батча. Границы
    решают: замер дал батчи размером `[1, 1, 4, 4, 10, …]`, то есть проекция,
    склеивающая по событию на вызов, выдала бы десять сообщений вместо одного.

    Граница — это факт («модель прислала один ход с десятью вызовами»), а не
    служебная метка, поэтому она выражена одним событием, а не полем «я первый в
    батче» у `ToolCallStarted`. `ToolCallStarted` остаётся ACP-фактом агента
    («вызов заявлен клиенту»), и смешивать в нём двух адресатов значило бы
    отменить разделение, сделанное шагом 3a.

    `content` — блок текста для ACP-чанка; `None`, когда модель прислала только
    вызовы (сегодня в этом случае чанк не эмитится вовсе).
    """

    content: dict[str, Any] | None = None
    tool_calls: list[RequestedToolCall] = field(default_factory=list)


@dataclass(frozen=True)
class ToolCallStarted:
    """Вызов инструмента заявлен.

    `status` — строка пространства ACP `ToolCallStatus`. Сужение до доменного
    `ToolCallStatus` отложено до шага 4, где статус становится проекцией: сегодня
    один из писателей (`prompt_orchestrator`, ретрансляция при resume) передаёт
    строку из чужой нотификации, и коэрция на горячем пути дала бы новую точку
    отказа там, где сейчас значение проходит дословно.

    `tool_name`, `arguments` и `tool_call_id_from_llm` ACP-формы не имеют и
    клиенту не уходят: они нужны, чтобы `tool_calls` стала проекцией журнала
    (шаг 4g ADR-008). Без них журнал вызов не восстанавливает — связки
    внутреннего `call_NNN` с идентификатором вызова у модели не несло ни одно
    событие, а `execute_pending` читает из восстановленного реестра ровно
    `tool_name` и `arguments`, и решение по разрешению переживает рестарт.

    Поля опциональны, потому что вызовы client-RPC (`prompt.client_requests`)
    инструментом не являются: у них нет ни имени, ни аргументов.
    """

    tool_call_id: str
    title: str
    kind: str
    status: str
    content: list[dict[str, Any]] | None = None
    tool_name: str | None = None
    arguments: dict[str, Any] | None = None
    tool_call_id_from_llm: str | None = None


@dataclass(frozen=True)
class ToolCallStatusChanged:
    """Статус вызова изменился; результат приложен, если он появился."""

    tool_call_id: str
    status: str
    content: list[dict[str, Any]] | None = None


@dataclass(frozen=True)
class ToolCallAnswered:
    """Модель получила ответ на вызов — ровно один факт на запись `role: tool`.

    Контракт LLM-API требует `role: tool` на каждый id из assistant-сообщения,
    поэтому ответ уходит и вызовам, которых нет ни в `tool_calls`, ни в остальных
    событиях журнала: остатку прерванного батча, отложенному хвосту после
    permission, вызову без имени инструмента.

    **Выполнялся вызов или нет — свойство статуса, а не ответа**, и оно уже
    выводимо из наличия `tool_call_started`. Поэтому событие одно: проекции
    достаётся одно правило («событие ответа → запись `role: tool`») вместо двух.
    Прежде видов было два, и различались они только этим (ADR-008, шаг 4a);
    старый вид записи (`unexecuted_tool_call_answered`) по-прежнему читается.

    Событие обязательно, потому что без него проекция `history` **невыводима**, и
    это замерено дважды, а не выведено:

    * ответы незарегистрированным вызовам — 26 записей `role=tool` против 23
      вызовов, затем 28/26 и 39/35 (шаг 4a);
    * `text` ответа выполненному вызову **не является функцией** ACP-контента:
      модели уезжает `output` исполнителя (плюс описание нетекстовых блоков), а в
      журнал — `content_items`, и совпадают они не всегда. Замер на двух
      документах с диска: 7 ответов из 30 и 2 из 5 текстом из журнала не
      выводились, класс — исполнитель, задающий контент явно (`terminal/create`
      говорит клиенту «Terminal … created for command …», а модели «Терминал
      создан с ID …»), результаты MCP с непустыми `content_items` и дописанное
      описание `image`/`audio`/`embedded`/`resource_link`.

    Собирать текст из контента (вариант B разбора) отклонено: это изменило бы то,
    что видит модель, и сбросило бы prompt cache внутри крупного шага. Писать
    событие только при расхождении — тоже: тогда отсутствие записи неотличимо от
    несработавшего писателя, а именно на этом дважды терялась приёмка (признак
    `waited` шага 5.1, пустой остаток шага 5.3).

    `tool_call_id` — адресат ответа (`answer_id`), то есть идентификатор из
    ответа модели, а не `ToolCallId` реестра: у незарегистрированного вызова
    сущности реестра нет вовсе.

    ACP-формы у события нет: `session/update` для tool-ответа модели не
    предусматривает — адресат этого факта LLM-история, а не клиент.
    """

    tool_call_id: str
    text: str


@dataclass(frozen=True)
class PlanRecorded:
    """Полный снимок плана. ACP передаёт план целиком, а не приращением."""

    entries: list[dict[str, Any]]


@dataclass(frozen=True)
class SessionInfoRecorded:
    """Метаданные сессии: заголовок и время активности.

    Единственное событие журнала **без** реплей-проекции: по ACP это
    патч-канал метаданных, а не conversation, и к моменту загрузки значение уже
    устарело — `session/load` в конце реплея эмитит свежее. Шаг 3a закрепляет
    это решение конструкцией: у события нет реплей-формы, вместо прежнего
    перечисления пяти видов из шести в наборе строк.
    """

    title: str | None
    updated_at: str | None


@dataclass(frozen=True)
class UnknownUpdateRecorded:
    """Запись журнала, которую модель не описывает — отдаётся дословно.

    Нужна терпимости к уже записанным сессиям: журнал писали и более ранние
    версии, и набор полей в их записях мог отличаться от нынешнего. Такая запись
    проходит проекцию без изменений, поэтому поток загрузки старой сессии
    остаётся байт-идентичным. Для того, что пишем мы, событие не возникает —
    это проверяется тестом.
    """

    update: dict[str, Any]


type SessionEvent = (
    UserMessageRecorded
    | AgentMessageRecorded
    | ToolCallStarted
    | ToolCallStatusChanged
    | ToolCallAnswered
    | PlanRecorded
    | SessionInfoRecorded
    | UnknownUpdateRecorded
)


@dataclass(frozen=True)
class JournalEntry:
    """Событие с меткой времени — единица журнала.

    Метка — поле журнала, а не факта диалога, поэтому она не участвует ни в одной
    проекции. `None` допустим: старая запись может её не иметь.
    """

    event: SessionEvent
    timestamp: datetime | None = None


@dataclass
class SessionJournal:
    """Журнал сессии — упорядоченная append-only коллекция событий (шаг 6a ADR-008).

    До этого шага журнал жил в `SessionRuntime` как `list[dict]` в **wire-форме**:
    домен хранил записи протокола, которых не понимал, а конвертировал их каждый
    читатель сам. Отсюда два следствия, которые шаг снимает.

    Первое: писатель, изменивший состояние и не дописавший событие, терял
    изменение молча — класс дефектов, найденный в 4f и 4g четырежды и закрытый
    структурными гейтами по `ast`. Гейт ловит непарного писателя, но не делает
    его невозможным; невозможным его делает единственный владелец дописывания.

    Второе: `seq`. Дописывать можно, только зная, какие события новые, а
    `list[dict]` курсора не несёт. Здесь `seq` — позиция записи, 1-based:
    журнал append-only, записи не удаляются и не переставляются, поэтому позиция
    устойчива и на диск отдельным полем не уезжает. Формат документа шаг не
    меняет — носитель меняет 6b.
    """

    _entries: list[JournalEntry] = field(default_factory=list)

    def append(self, event: SessionEvent, timestamp: datetime | None = None) -> int:
        """Дописать событие; возвращает его `seq`.

        Единственный способ пополнить журнал: `entries()` отдаёт кортеж, поэтому
        дописать мимо этого метода нельзя даже по неосторожности.
        """
        self._entries.append(JournalEntry(event=event, timestamp=timestamp))
        return len(self._entries)

    def entries(self) -> tuple[JournalEntry, ...]:
        """Все записи в хронологическом порядке."""
        return tuple(self._entries)

    def after(self, seq: int) -> tuple[JournalEntry, ...]:
        """Записи с `seq` больше указанного — то, что осталось дописать.

        Потребитель появится в 6b (`append_events` с курсором последнего
        сохранённого `seq`); метод вводится здесь вместе с `seq`, потому что
        именно он объясняет, зачем `seq` нужен.
        """
        return tuple(self._entries[max(seq, 0) :])

    def restore(self, entries: Iterable[JournalEntry]) -> None:
        """Заполнить журнал при сборке агрегата из документа.

        Отдельно от `append`: восстановление несёт метки времени с диска, а
        `append` ставит свои. Зовёт только маппер.
        """
        self._entries = list(entries)

    @property
    def last_seq(self) -> int:
        """`seq` последней записи; 0 — журнал пуст."""
        return len(self._entries)

    def __len__(self) -> int:
        return len(self._entries)
