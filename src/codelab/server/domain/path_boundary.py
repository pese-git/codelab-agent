"""Граница рабочего каталога — одно правило вместо рукописной проверки в обработчиках.

ADR-009, шаг 2б. Правило «путь инвокации не выходит за рабочий каталог сессии»
существовало и раньше, но было написано руками в двух обработчиках `fs/*`: его
получал тот инструмент, чей автор о нём вспомнил, и новый файловый инструмент не
получил бы ничего — тот же класс, что `terminal_counter` (P2-58).

Здесь оно становится одним выражением, которое применяет шов исполнения
(`ToolRegistry.execute_tool`) ко всякой инвокации с путём, независимо от
вызывающего. Правило чистое — ни ввода-вывода, ни зависимости от протокола,
поэтому живёт в домене рядом с `ToolInvocationSubject`.

**Вне каталога — отказ, а не запрос разрешения.** Первая редакция ADR (раздел 4)
обещала `Ask` для модели; по коду это оказалось не переносом, а ослаблением:
сегодня обработчик отказывает, вызов становится `failed`, и так наблюдалось
живьём (`sess_d6501a707159`, галлюцинация `/home/user/app/README.md`). Решение
2026-08-11: сохранить отказ; «пускать ли модель вне каталога по разрешению» —
отдельный вопрос, решаемый вместе с форматом правил allow/deny.
"""

from __future__ import annotations

from pathlib import Path


def normalize_path(cwd: str, path: str) -> str:
    """Привести путь к абсолютному относительно рабочего каталога.

    Абсолютный путь возвращается как есть — иначе выход за каталог стал бы
    невыразимым, и правило границы проверяло бы само себя.

    Args:
        cwd: Рабочий каталог сессии.
        path: Путь к файлу (абсолютный или относительный).

    Returns:
        Нормализованный абсолютный путь.
    """
    p = Path(path)
    if p.is_absolute():
        return path
    return str(Path(cwd) / p)


def is_inside_cwd(path: str, cwd: str) -> bool:
    """Находится ли путь внутри рабочего каталога.

    Сравнение по строкам разрешённых путей: `resolve()` снимает `..` и symlink,
    из-за которых проверка по исходной строке обходится тривиально.

    Args:
        path: Абсолютный путь к файлу.
        cwd: Рабочий каталог сессии.

    Returns:
        `True`, если путь внутри каталога.
    """
    return str(Path(path).resolve()).startswith(str(Path(cwd).resolve()))


def outside_cwd_error(path: str, cwd: str) -> str:
    """Текст отказа для вышедшего за каталог пути.

    Текст уходит модели в теле `role: tool` и сохранён дословно: он уже
    наблюдался в живых прогонах, а изменение сдвинуло бы LLM-payload.

    Args:
        path: Путь, вызвавший отказ (в исходном виде, как его назвал вызывающий).
        cwd: Рабочий каталог сессии.

    Returns:
        Причина отказа.
    """
    return (
        f"Path '{path}' is outside working directory '{cwd}'. "
        f"Use relative paths or terminal commands (ls, find) to discover files."
    )
